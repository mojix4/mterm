    }

    buildTypes {
        release {
            // One fixed key so new versions install over old ones.
            signingConfig = if (keyFile.exists()) signingConfigs.getByName("release") else signingConfigs.getByName("debug")
            isMinifyEnabled = false
            isShrinkResources = false
        }
